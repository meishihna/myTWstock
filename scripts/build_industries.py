"""build_industries.py — 「產業」section(櫃買中心 TPEx 產業價值鏈)資料生成。
與 /map 投資題材(build_themes.py)完全分離。結構參照 ic.tpex.org.tw。

TPEX_INDUSTRIES[key] = {
    name, desc, category(頂層 tile 名), indicators, members:{tier:{node:[ticker]}}
}
輸出 industries/<key>.md(供 web/scripts/build-industries-index.mjs 取用)。
重建:python scripts/build_industries.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
REPORTS_DIR = os.path.join(REPO, "Pilot_Reports")
OUT_DIR = os.path.join(REPO, "industries")
TIER_ZH = {"upstream": "上游", "midstream": "中游", "downstream": "下游"}
_FNAME_RE = re.compile(r"^(\d{4})_(.+)\.md$")


def scan_ticker_meta():
    meta = {}
    if not os.path.isdir(REPORTS_DIR):
        return meta
    for sector in os.listdir(REPORTS_DIR):
        sd = os.path.join(REPORTS_DIR, sector)
        if not os.path.isdir(sd):
            continue
        for fn in os.listdir(sd):
            m = _FNAME_RE.match(fn)
            if m:
                meta[m.group(1)] = {"company": m.group(2), "sector": sector}
    return meta


def _format(entries):
    # 節點依來源(TPEx)順序分組;「其他」/無子分類排最後;組內 產業→代號
    order = {}
    for e in entries:
        s = (e["subcat"] or "").strip()
        if s and s != "其他" and s not in order:
            order[s] = len(order)
    big = len(order) + 10

    def key(e):
        s = (e["subcat"] or "").strip()
        rank = big + 1 if not s else (big if s == "其他" else order[s])
        return (rank, e["sector"], e["ticker"])

    out = []
    for e in sorted(entries, key=key):
        suf = " [" + e["subcat"] + "]" if e["subcat"] else ""
        out.append("- **" + e["ticker"] + " " + e["company"] + "** (" + e["sector"] + ")" + suf)
    return out


def build_industry_page(defn, meta):
    members = defn["members"]
    entries, seen = [], set()
    for tier in ("upstream", "midstream", "downstream"):
        group = members.get(tier)
        if not group:
            continue
        for node, tickers in group.items():  # dict 順序 = TPEx 節點順序
            for tk in tickers:
                if tk in seen:
                    continue
                m = meta.get(tk)
                if not m:
                    continue
                seen.add(tk)
                entries.append({"ticker": tk, "company": m["company"],
                                "sector": m["sector"], "role": tier, "subcat": node})
    if not entries:
        return None
    flat = list(members.keys()) == ["midstream"]  # 服務型單層(航運/區塊鏈/文創…)

    lines = ["# " + defn["name"], "", "> " + defn["desc"], "",
             "**涵蓋公司數:** " + str(len(entries)), "", "**分類:** " + defn["category"], ""]
    if flat:
        lines += ["**型態:** flat", ""]
    if defn.get("indicators"):
        joined = " | ".join(d["label"] + "=" + d["value"] for d in defn["indicators"])
        lines += ["**關鍵指標:** " + joined, ""]
    lines += ["---", ""]
    for tier in ("upstream", "midstream", "downstream"):
        ts = [e for e in entries if e["role"] == tier]
        if ts:
            lines += ["## " + TIER_ZH[tier] + " (" + str(len(ts)) + ")", ""] + _format(ts) + [""]
    return "\n".join(lines)


def main():
    if sys.platform == "win32":
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    os.makedirs(OUT_DIR, exist_ok=True)
    meta = scan_ticker_meta()
    built = 0
    for key, defn in TPEX_INDUSTRIES.items():
        page = build_industry_page(defn, meta)
        if not page:
            print("  [skip] " + key + ": 無涵蓋公司")
            continue
        with open(os.path.join(OUT_DIR, key + ".md"), "w", encoding="utf-8") as f:
            f.write(page)
        built += 1
        print("  " + key + ": " + defn["name"])
    print("\nDone. " + str(built) + " industries -> industries/")


